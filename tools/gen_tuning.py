#!/usr/bin/env python3
"""Generates sim/tuning.gd from data/tuning.json (written by the Swift oracle).

Swift writes Doubles with a decimal point or exponent and Ints without, and Python's json keeps
that distinction, so every field gets its exact GDScript type. Run after `oracle export`.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def snake(name: str) -> str:
    """Swift camelCase → GDScript snake_case. Mirrored by Canon.snake() in sim/canon.gd."""
    out = []
    for i, c in enumerate(name):
        if c.isupper() and i > 0:
            prev = name[i - 1]
            nxt = name[i + 1] if i + 1 < len(name) else ""
            if prev.islower() or prev.isdigit() or (prev.isupper() and nxt.islower()):
                out.append("_")
        out.append(c.lower())
    return "".join(out)


def main() -> None:
    data = json.load(open(os.path.join(ROOT, "data/tuning.json")))
    scalars, ranges, specs = [], [], []
    for k, v in data.items():
        if isinstance(v, bool):
            scalars.append((k, "bool"))
        elif isinstance(v, int):
            scalars.append((k, "int"))
        elif isinstance(v, float):
            scalars.append((k, "float"))
        elif isinstance(v, dict) and set(v) == {"lowerBound", "upperBound"}:
            ranges.append(k)
        elif isinstance(v, dict) and "attacks" in v:
            specs.append(k)
        else:
            sys.exit(f"gen_tuning: unhandled field {k}: {v!r}")

    L = [
        "class_name Tuning",
        "extends RefCounted",
        "## Every number that decides how the game feels. GENERATED by tools/gen_tuning.py from",
        "## data/tuning.json; do not edit by hand. Field names are the Swift ones in snake_case.",
        "",
        "const FRAMES_PER_SECOND := 60.0",
        "",
    ]
    for k, t in scalars:
        L.append(f"var {snake(k)}: {t}")
    L.append("")
    for k in ranges:
        L.append(f"var {snake(k)}: Specs.IntRange")
    L.append("")
    for k in specs:
        L.append(f"var {snake(k)}: Specs.FighterSpec")
    L += [
        "",
        "",
        "static func load_default() -> Tuning:",
        '\treturn from_data(JSON.parse_string(FileAccess.get_file_as_string("res://data/tuning.json")))',
        "",
        "",
        "static func from_data(d: Dictionary) -> Tuning:",
        "\tvar t := Tuning.new()",
    ]
    for k, typ in scalars:
        L.append(f"\tt.{snake(k)} = {typ}(d[\"{k}\"])")
    for k in ranges:
        L.append(f"\tt.{snake(k)} = Specs.IntRange.from_data(d[\"{k}\"])")
    for k in specs:
        L.append(f"\tt.{snake(k)} = Specs.FighterSpec.from_data(d[\"{k}\"])")
    L += [
        "\treturn t",
        "",
        "",
        "## The spec for a fighter kind, by its Swift case name (\"scrapDrone\").",
        "func spec(kind: String) -> Specs.FighterSpec:",
        "\tmatch kind:",
    ]
    for k in specs:
        L.append(f'\t\t"{k}":')
        L.append(f"\t\t\treturn {snake(k)}")
    L += ['\tpush_error("Tuning: no spec for %s" % kind)', "\treturn null", ""]
    open(os.path.join(ROOT, "sim/tuning.gd"), "w").write("\n".join(L))
    print(f"sim/tuning.gd: {len(scalars)} scalars, {len(ranges)} ranges, {len(specs)} specs")


if __name__ == "__main__":
    main()
